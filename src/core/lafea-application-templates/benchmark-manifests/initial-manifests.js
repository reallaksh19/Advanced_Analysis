import {
  createTemplateBenchmarkManifest,
  asciiCompare,
} from '../contracts.js';
import {
  LAFEA_APPLICATION_TEMPLATE_REGISTRY,
} from '../template-registry.js';

const BUCKET_MANIFEST_IDS = Object.freeze({
  ANALYTICAL_MECHANICS: 'BM-BUCKET-A-ANALYTICAL-V1',
  CONTINUUM_2D_FEA: 'BM-BUCKET-B-CONTINUUM-V1',
  RECOVERY_ASSESSMENT: 'BM-PLANE-D-RECOVERY-ASSESSMENT-V1',
  SURFACE_SHELL_FEA: 'BM-BUCKET-C-SHELL-V1',
});

export const LAFEA_INITIAL_TEMPLATE_BENCHMARK_MANIFESTS = Object.freeze(
  LAFEA_APPLICATION_TEMPLATE_REGISTRY.map((template) => createInitialManifest(template))
    .sort((left, right) => asciiCompare(left.benchmarkManifestId, right.benchmarkManifestId)),
);

export function requireInitialTemplateBenchmarkManifest(benchmarkManifestId) {
  const result = LAFEA_INITIAL_TEMPLATE_BENCHMARK_MANIFESTS
    .find((manifest) => manifest.benchmarkManifestId === benchmarkManifestId);
  if (!result) {
    throw new TypeError(`Unknown initial template benchmark manifest: ${benchmarkManifestId}.`);
  }
  return result;
}

function createInitialManifest(template) {
  return createTemplateBenchmarkManifest({
    benchmarkManifestId: template.benchmarkManifestId,
    templateId: template.templateId,
    bucketId: template.bucketId,
    revision: 1,
    parentRegistryHash: template.parentRegistryHash,
    bucketBenchmarkManifestId: BUCKET_MANIFEST_IDS[template.bucketId],
    benchmarks: benchmarkCases(template),
    qualificationStatus:
      template.releaseStatus === 'BLOCKED' ? 'BLOCKED' : 'NOT_QUALIFIED',
    limitations: [
      'Expected evidence is not generated by the production compiler.',
      'Independent expected-result hashes are unresolved in T1.',
      'The manifest cannot qualify a template until every required case passes at exact head.',
    ],
  });
}

function benchmarkCases(template) {
  const cases = [
    caseRecord(template, 'PARAM-01', 'PARAMETER_BOUNDARY'),
    caseRecord(template, 'GEOMETRY-01', 'GEOMETRY_FEATURE'),
    caseRecord(template, 'LOAD-01', 'LOAD_RECONSTRUCTION'),
    caseRecord(template, 'BOUNDARY-01', 'BOUNDARY_RECONSTRUCTION'),
    caseRecord(template, 'INVARIANCE-01', 'ROTATION_UNIT_ORDER_INVARIANCE'),
    caseRecord(template, 'HASH-01', 'DETERMINISM'),
    caseRecord(template, 'HANDOFF-01', 'STAGE_HANDOFF'),
    caseRecord(template, 'BUCKET-PARENT-01', 'BUCKET_PARENT_IDENTITY'),
    caseRecord(template, 'FAIL-01', 'UNSUPPORTED_COMBINATION'),
  ];

  if (['CONTINUUM_2D_FEA', 'SURFACE_SHELL_FEA'].includes(template.bucketId)) {
    cases.push(caseRecord(template, 'MESH-REQUEST-01', 'MESH_REQUEST'));
  }
  if (template.bucketId === 'RECOVERY_ASSESSMENT') {
    cases.push(caseRecord(template, 'RECOVERY-REQUEST-01', 'RECOVERY_REQUEST'));
  }

  return cases;
}

function caseRecord(template, suffix, category) {
  return {
    benchmarkId: `${template.templateId}-${suffix}`,
    category,
    evidenceBasis: 'UNRESOLVED',
    expectedResultHash: null,
    sourceRef: {
      document:
        'LAFEA_Application_Template_and_Computational_Bucket_Architecture_Concept_Note',
      section: '12.2 Template compiler benchmarks',
    },
    toleranceProfileId: null,
    status: 'UNRESOLVED',
  };
}
