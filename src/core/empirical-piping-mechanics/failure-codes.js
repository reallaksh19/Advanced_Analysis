export class EmpiricalPipingError extends Error {
  constructor(code, message, evidence = {}) {
    super(message);
    this.name = 'EmpiricalPipingError';
    this.code = code;
    this.evidence = Object.freeze({ ...evidence });
  }
}

export function empiricalFailure(code, message, evidence = {}) {
  return new EmpiricalPipingError(code, message, evidence);
}
