import { freezeDeep } from '../dataset-utils.js';
import { projectDataValue } from '../project-data/project-data-contract.js';

export const ROUTE_PARTITION_MODEL_SCHEMA = 'route-partition-model/v1';

/**
 * Builds branch-scoped connected routes from exact component ports. Source
 * order is never used to invent chainage. Approximate port joining requires an
 * approved Project Data tolerance.
 */
export function buildRoutePartitionModel(dataset, profile) {
  assertDataset(dataset);
  const tolerance = projectDataValue(profile, 'topology.portMatchToleranceMm');
  const routeJoiningRules = projectDataValue(profile, 'topology.routeJoiningRules');
  const edges = dataset.entities.map(toEdge).filter(Boolean);
  classifyAutoCarriers(edges, projectDataValue(profile, 'topology.autoCarrierCoincidenceToleranceMm'));
  const byBranch = groupBy(edges, (edge) => edge.branchId || 'UNASSIGNED');
  const routes = [...byBranch.entries()].flatMap(([branchId, branchEdges]) => connectedRoutes(branchId, branchEdges, tolerance));
  const blockers = [];
  if (!Number.isFinite(tolerance)) blockers.push({ code: 'MISSING_PORT_MATCH_TOLERANCE', projectDataPath: 'topology.portMatchToleranceMm' });
  if (!Number.isFinite(projectDataValue(profile, 'topology.autoCarrierCoincidenceToleranceMm'))) {
    blockers.push({ code: 'MISSING_AUTO_CARRIER_TOLERANCE', projectDataPath: 'topology.autoCarrierCoincidenceToleranceMm' });
  }
  if (!supportedRouteJoiningRules(routeJoiningRules)) {
    blockers.push({ code: 'UNSUPPORTED_ROUTE_JOINING_RULES', projectDataPath: 'topology.routeJoiningRules' });
  }
  return freezeDeep({
    schema: ROUTE_PARTITION_MODEL_SCHEMA,
    datasetId: dataset.datasetId,
    portMatchToleranceMm: Number.isFinite(tolerance) ? tolerance : null,
    routeJoiningRules: routeJoiningRules || null,
    status: blockers.length ? 'BLOCKED' : 'READY',
    blockers,
    routes,
    edges,
    summary: {
      routeCount: routes.length,
      edgeCount: edges.length,
      physicalEdgeCount: edges.filter((edge) => edge.physical).length,
      autoCarrierCount: edges.filter((edge) => edge.topologyCarrier).length,
    },
  });
}

function toEdge(entity) {
  if (entity.category === 'support' || entity.entityType === 'BRANCH') return null;
  const start = entity.properties?.geometry?.start;
  const end = entity.properties?.geometry?.end;
  if (!start || !end) return null;
  return {
    edgeId: entity.entityId,
    entityId: entity.entityId,
    branchId: entity.branchId,
    lineKey: entity.lineKey,
    entityType: entity.entityType,
    startMm: start,
    endMm: end,
    lengthMm: distance(start, end),
    pointComponent: distance(start, end) === 0,
    autoGenerated: String(entity.properties?.attributes?.AUTO_GENERATED_PIPE).toLowerCase() === 'true',
    topologyCarrier: false,
    physical: true,
    source: { sourceEntityId: entity.sourceEntityId, jsonPointer: entity.jsonPointer, componentReference: entity.componentReference },
  };
}

function classifyAutoCarriers(edges, tolerance) {
  edges.filter((edge) => edge.autoGenerated).forEach((edge) => {
    const overlap = edges.some((other) => other !== edge && !other.autoGenerated
      && sameEndpoints(edge, other, tolerance));
    if (overlap) { edge.topologyCarrier = true; edge.physical = false; }
  });
}

function connectedRoutes(branchId, edges, tolerance) {
  const remaining = new Set(edges.map((edge) => edge.edgeId));
  const byId = new Map(edges.map((edge) => [edge.edgeId, edge]));
  const routes = [];
  while (remaining.size) {
    const seedId = [...remaining].sort()[0];
    const component = [];
    const queue = [byId.get(seedId)];
    remaining.delete(seedId);
    while (queue.length) {
      const edge = queue.shift();
      component.push(edge);
      edges.forEach((candidate) => {
        if (!remaining.has(candidate.edgeId) || !touches(edge, candidate, tolerance)) return;
        remaining.delete(candidate.edgeId); queue.push(candidate);
      });
    }
    routes.push(createRoute(branchId, routes.length, component, tolerance));
  }
  return routes;
}

function createRoute(branchId, index, edges, tolerance) {
  const topologyEdges = edges.filter((edge) => !edge.topologyCarrier && !edge.pointComponent);
  const nodes = uniqueNodes(topologyEdges, tolerance);
  const degrees = nodes.map((node) => ({ ...node, degree: topologyEdges.filter((edge) => pointOnEdgeEnd(node.positionMm, edge, tolerance)).length }));
  const ambiguous = degrees.some((node) => node.degree > 2);
  const chainage = ambiguous ? { entityChainages: [], totalLengthMm: null } : buildLinearChainage(topologyEdges, degrees, edges, tolerance);
  return freezeDeep({
    routeId: `route:${branchId}:${index + 1}`,
    branchId,
    lineKey: edges.find((edge) => edge.lineKey)?.lineKey || '',
    status: ambiguous ? 'BLOCKED' : 'READY',
    blockers: ambiguous ? [{ code: 'BRANCHED_CHAINAGE_REQUIRES_ROUTE_JOINING_RULE', nodes: degrees.filter((node) => node.degree > 2).map((node) => node.nodeId) }] : [],
    nodes: degrees,
    edgeIds: edges.map((edge) => edge.edgeId),
    physicalEdgeIds: edges.filter((edge) => edge.physical).map((edge) => edge.edgeId),
    entityChainages: chainage.entityChainages,
    totalLengthMm: chainage.totalLengthMm,
  });
}

function buildLinearChainage(topologyEdges, nodes, allEdges, tolerance) {
  if (!topologyEdges.length) return { entityChainages: [], totalLengthMm: 0 };
  const endpoints = nodes.filter((node) => node.degree === 1).sort((left, right) => left.nodeId.localeCompare(right.nodeId));
  const startNode = endpoints[0] || [...nodes].sort((left, right) => left.nodeId.localeCompare(right.nodeId))[0];
  const nodeChainage = new Map([[startNode.nodeId, 0]]);
  const unvisited = new Set(topologyEdges.map((edge) => edge.edgeId));
  const ordered = [];
  let current = startNode;
  while (unvisited.size) {
    const edge = topologyEdges.find((candidate) => unvisited.has(candidate.edgeId) && pointOnEdgeEnd(current.positionMm, candidate, tolerance));
    if (!edge) break;
    unvisited.delete(edge.edgeId);
    const nextPoint = samePoint(current.positionMm, edge.startMm, tolerance) ? edge.endMm : edge.startMm;
    const next = nodes.find((node) => samePoint(node.positionMm, nextPoint, tolerance));
    const startMm = nodeChainage.get(current.nodeId);
    const endMm = startMm + edge.lengthMm;
    nodeChainage.set(next.nodeId, endMm);
    const followsSource = samePoint(current.positionMm, edge.startMm, tolerance);
    ordered.push({
      entityId: edge.entityId, startMm, endMm,
      sourceStartChainageMm: followsSource ? startMm : endMm,
      sourceEndChainageMm: followsSource ? endMm : startMm,
      pointMm: (startMm + endMm) / 2,
    });
    current = next;
  }
  const totalLengthMm = Math.max(0, ...nodeChainage.values());
  const pointRows = allEdges.filter((edge) => edge.pointComponent).map((edge) => {
    const node = nodes.find((candidate) => samePoint(candidate.positionMm, edge.startMm, tolerance));
    const pointMm = node ? nodeChainage.get(node.nodeId) : null;
    return { entityId: edge.entityId, startMm: pointMm, endMm: pointMm, sourceStartChainageMm: pointMm, sourceEndChainageMm: pointMm, pointMm };
  });
  const carrierRows = allEdges.filter((edge) => edge.topologyCarrier).map((edge) => {
    const start = nodes.find((node) => samePoint(node.positionMm, edge.startMm, tolerance));
    const end = nodes.find((node) => samePoint(node.positionMm, edge.endMm, tolerance));
    const startMm = start ? nodeChainage.get(start.nodeId) : null;
    const endMm = end ? nodeChainage.get(end.nodeId) : null;
    return { entityId: edge.entityId, startMm, endMm, sourceStartChainageMm: startMm, sourceEndChainageMm: endMm, pointMm: Number.isFinite(startMm) && Number.isFinite(endMm) ? (startMm + endMm) / 2 : null };
  });
  return { entityChainages: [...ordered, ...pointRows, ...carrierRows], totalLengthMm };
}

function uniqueNodes(edges, tolerance) {
  const nodes = [];
  edges.flatMap((edge) => [edge.startMm, edge.endMm]).forEach((point) => {
    if (!nodes.some((node) => samePoint(node.positionMm, point, tolerance))) {
      nodes.push({ nodeId: `port:${pointKey(point)}`, positionMm: point });
    }
  });
  return nodes;
}

function touches(a, b, tolerance) { return [a.startMm, a.endMm].some((left) => [b.startMm, b.endMm].some((right) => samePoint(left, right, tolerance))); }
function pointOnEdgeEnd(point, edge, tolerance) { return samePoint(point, edge.startMm, tolerance) || samePoint(point, edge.endMm, tolerance); }
function sameEndpoints(a, b, tolerance) { return (samePoint(a.startMm, b.startMm, tolerance) && samePoint(a.endMm, b.endMm, tolerance)) || (samePoint(a.startMm, b.endMm, tolerance) && samePoint(a.endMm, b.startMm, tolerance)); }
function samePoint(a, b, tolerance) { if (!Number.isFinite(tolerance)) return pointKey(a) === pointKey(b); return distance(a, b) <= tolerance; }
function pointKey(point) { return `${point.x}|${point.y}|${point.z}`; }
function distance(a, b) { return Math.hypot(a.x - b.x, a.y - b.y, a.z - b.z); }
function groupBy(rows, keyOf) { const map = new Map(); rows.forEach((row) => { const key = keyOf(row); if (!map.has(key)) map.set(key, []); map.get(key).push(row); }); return map; }
function supportedRouteJoiningRules(value) { return value?.partition === 'branch-scoped-connected-components' && value?.chainage === 'exact-port-topology' && value?.sourceOrderAllowed === false && value?.degreeAboveTwo === 'BLOCKED'; }
function assertDataset(dataset) { if (!dataset?.datasetId || !Array.isArray(dataset.entities)) throw new TypeError('Route partition requires a workspace dataset.'); }
